def sprache():
    kandidaten = [os.environ.get(v, "") for v in ("LANGUAGE", "LC_ALL", "LC_MESSAGES", "LANG")]
    try:
        kandidaten.append(locale.getlocale()[0] or "")
    except ValueError:
        pass
    for wert in kandidaten:
        kürzel = wert.split(":")[0].split("_")[0].split(".")[0].lower()
        if kürzel in SPRACHEN:
            return kürzel
    return "en"


AKTIV = sprache()


def t(schlüssel, **werte):
    text = SPRACHEN.get(AKTIV, {}).get(schlüssel) or SPRACHEN["en"][schlüssel]
    return text.format(**werte) if werte else text
